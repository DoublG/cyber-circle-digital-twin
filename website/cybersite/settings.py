"""Settings of the Cyber Circle Challenge website (registration + scoreboard).
Everything that differs per host comes from environment variables (.env.example):
    DJANGO_SECRET_KEY      required when DJANGO_DEBUG is off
    DJANGO_DEBUG           1 = development (default 0)
    DJANGO_ALLOWED_HOSTS   comma separated, e.g. cyberchallenge.coderdojobelgium.be
    DJANGO_CSRF_TRUSTED_ORIGINS  e.g. https://cyberchallenge.coderdojobelgium.be
    DATABASE_URL           default: SQLite next to manage.py (postgres://... in production)
    SYNC_TOKEN             the shared secret of the installation's control server (the sync API)
"""
import os
from pathlib import Path

import dj_database_url

BASE_DIR = Path(__file__).resolve().parent.parent


def env_bool(name, default=False):
    return os.environ.get(name, "1" if default else "0").lower() in ("1", "true", "yes", "on")


DEBUG = env_bool("DJANGO_DEBUG")
SECRET_KEY = os.environ.get("DJANGO_SECRET_KEY") or ("dev-only-not-secret" if DEBUG else "")
if not SECRET_KEY:
    raise RuntimeError("DJANGO_SECRET_KEY is not set (or DJANGO_DEBUG=1 for development)")
ALLOWED_HOSTS = [h.strip() for h in os.environ.get("DJANGO_ALLOWED_HOSTS", "localhost,127.0.0.1").split(",") if h.strip()]
CSRF_TRUSTED_ORIGINS = [o.strip() for o in os.environ.get("DJANGO_CSRF_TRUSTED_ORIGINS", "").split(",") if o.strip()]
SYNC_TOKEN = os.environ.get("SYNC_TOKEN", "")

INSTALLED_APPS = [
    "django.contrib.admin",
    "django.contrib.auth",
    "django.contrib.contenttypes",
    "django.contrib.sessions",
    "django.contrib.messages",
    "django.contrib.staticfiles",
    "challenge",
]

